import React, { useState } from 'react';
import { BookOpen, Edit2, AlertTriangle, Check, X, Shield, Sparkles } from 'lucide-react';
import { apiClient } from '../api/client';

interface KeyPoint {
  point: string;
  marks: number;
  accept_if?: string;
  reject_if?: string;
}

interface ReferenceData {
  model_answer: string;
  key_points: KeyPoint[];
  correct_option?: string | null;
  source: string; // 'teacher_key' | 'ai_draft'
}

interface ReferenceCardProps {
  paperId: string;
  questionKey: string;
  reference?: ReferenceData;
  questionType?: string;
  options?: string[];
  strictness?: string;
  onReferenceUpdated?: () => void;
  onError?: (err: { code: string; message: string }) => void;
}

export const ReferenceCard: React.FC<ReferenceCardProps> = ({
  paperId,
  questionKey,
  reference,
  questionType,
  options = [],
  strictness = 'lenient',
  onReferenceUpdated,
  onError,
}) => {
  const [isDrawerOpen, setIsDrawerOpen] = useState(false);
  const [editModelAnswer, setEditModelAnswer] = useState(reference?.model_answer || '');
  const [editCorrectOption, setEditCorrectOption] = useState(reference?.correct_option || '');
  const [isSaving, setIsSaving] = useState(false);

  const isTeacherKey = reference?.source === 'teacher_key';
  const isAiDraft = reference?.source === 'ai_draft' || !reference?.source;

  const handleOpenDrawer = () => {
    setEditModelAnswer(reference?.model_answer || '');
    setEditCorrectOption(reference?.correct_option || '');
    setIsDrawerOpen(true);
  };

  const handleSaveReference = async () => {
    setIsSaving(true);
    try {
      await apiClient.put(`/api/papers/${paperId}/questions/${questionKey}/reference`, {
        model_answer: editModelAnswer.trim(),
        key_points: reference?.key_points || [],
        correct_option: editCorrectOption.trim() || undefined,
      });
      setIsDrawerOpen(false);
      onReferenceUpdated?.();
    } catch (err: any) {
      onError?.({
        code: err.code || 'REF_UPDATE_FAILED',
        message: err.message || 'Failed to update question reference.',
      });
    } finally {
      setIsSaving(false);
    }
  };

  return (
    <section
      aria-label="Rubric Reference"
      className="border border-[var(--surface-border)] rounded-lg bg-[var(--surface-card)] flex flex-col min-h-0 h-full overflow-hidden relative"
    >
      {/* Header */}
      <div className="px-3 py-2 bg-[var(--surface-canvas)] border-b border-[var(--surface-border)] flex items-center justify-between gap-2 shrink-0">
        <div className="flex items-center gap-2">
          <BookOpen className="w-3.5 h-3.5 text-[var(--accent-indigo)]" />
          <h4 className="text-xs font-semibold text-[var(--ink-primary)] uppercase tracking-wider">
            2. Reference
          </h4>
        </div>

        <div className="flex items-center gap-1.5">
          {/* Source Badge */}
          {isTeacherKey ? (
            <span className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-[var(--status-approved-bg)] text-[var(--status-approved)] border border-[var(--status-approved-border)]">
              Teacher key
            </span>
          ) : (
            <span className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-[var(--status-flagged-bg)] text-[var(--status-flagged)] border border-[var(--status-flagged-border)]">
              AI reference
            </span>
          )}

          {/* Strictness Chip */}
          <span className="text-[10px] font-medium px-2 py-0.5 rounded-full bg-[var(--surface-subtle)] text-[var(--ink-muted)] border border-[var(--surface-border)] capitalize">
            {strictness}
          </span>

          {/* Edit Reference Button */}
          <button
            type="button"
            onClick={handleOpenDrawer}
            className="p-1 rounded text-[var(--ink-muted)] hover:text-[var(--accent-indigo)] hover:bg-[var(--surface-subtle)] transition"
            title="Edit question reference"
          >
            <Edit2 className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* AI Draft Warning Note */}
      {isAiDraft && (
        <div className="px-3 py-1.5 bg-[var(--status-flagged-bg)] border-b border-[var(--status-flagged-border)] text-[11px] text-[var(--status-flagged)] flex items-center gap-1.5 shrink-0">
          <AlertTriangle className="w-3.5 h-3.5 shrink-0" />
          <span>Generated by AI, verify before relying on it</span>
        </div>
      )}

      {/* Content: Model Answer & Rubric Points */}
      <div className="panel flex-1 p-3 overflow-y-auto space-y-3 text-xs leading-relaxed">
        {/* Correct Option for MCQ/Objective */}
        {reference?.correct_option && (
          <div className="p-2 rounded bg-[var(--status-approved-bg)] border border-[var(--status-approved-border)] flex items-center justify-between">
            <span className="text-[10px] font-bold text-[var(--status-approved)] uppercase tracking-wider">
              Correct Option:
            </span>
            <span className="text-xs font-semibold text-[var(--status-approved)] font-mono">
              {reference.correct_option}
            </span>
          </div>
        )}

        {/* Model Answer */}
        <div>
          <span className="text-[10px] font-bold text-[var(--ink-muted)] uppercase tracking-wider block mb-1">
            Model Answer:
          </span>
          <p className="text-[var(--ink-primary)] whitespace-pre-wrap font-sans bg-[var(--surface-canvas)] p-2 rounded border border-[var(--surface-border-subtle)]">
            {reference?.model_answer || (
              <span className="text-[var(--ink-muted)] italic">No model answer defined.</span>
            )}
          </p>
        </div>

        {/* MCQ Options (if question type is MCQ) */}
        {options.length > 0 && (
          <div>
            <span className="text-[10px] font-bold text-[var(--ink-muted)] uppercase tracking-wider block mb-1">
              Options:
            </span>
            <div className="space-y-1">
              {options.map((opt, i) => (
                <div
                  key={i}
                  className="px-2 py-1 rounded border border-[var(--surface-border)] bg-[var(--surface-subtle)] text-[11px]"
                >
                  {opt}
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Rubric Key Points */}
        {reference?.key_points && reference.key_points.length > 0 && (
          <div>
            <span className="text-[10px] font-bold text-[var(--ink-muted)] uppercase tracking-wider block mb-1.5">
              Rubric Key Points:
            </span>
            <div className="space-y-1.5">
              {reference.key_points.map((kp, idx) => (
                <div
                  key={idx}
                  className="p-2 rounded border border-[var(--surface-border)] bg-[var(--surface-canvas)] text-[11px]"
                >
                  <div className="flex items-start justify-between gap-2 font-medium text-[var(--ink-primary)]">
                    <span>
                      {idx + 1}. {kp.point}
                    </span>
                    <span className="tabular-nums font-bold text-[var(--accent-indigo)] shrink-0">
                      +{kp.marks}M
                    </span>
                  </div>
                  {(kp.accept_if || kp.reject_if) && (
                    <div className="mt-1 pt-1 border-t border-[var(--surface-border-subtle)] text-[10px] space-y-0.5 text-[var(--ink-muted)]">
                      {kp.accept_if && (
                        <div className="text-[var(--status-approved)]">
                          ✔ Accept: {kp.accept_if}
                        </div>
                      )}
                      {kp.reject_if && (
                        <div className="text-[var(--status-failed)]">
                          ✘ Reject: {kp.reject_if}
                        </div>
                      )}
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        )}
      </div>

      {/* Slide-over Drawer for Editing Reference */}
      {isDrawerOpen && (
        <div className="absolute inset-0 bg-[var(--surface-card)] z-30 flex flex-col p-4 shadow-xl">
          <div className="flex items-center justify-between pb-3 border-b border-[var(--surface-border)] mb-3">
            <h5 className="text-xs font-bold text-[var(--ink-primary)] uppercase tracking-wider">
              Edit Model Reference
            </h5>
            <button
              type="button"
              onClick={() => setIsDrawerOpen(false)}
              className="p-1 rounded text-[var(--ink-muted)] hover:text-[var(--ink-primary)]"
            >
              <X className="w-4 h-4" />
            </button>
          </div>

          <div className="flex-1 flex flex-col gap-2 min-h-0">
            {(options.length > 0 || questionType === 'mcq') && (
              <div className="flex flex-col gap-1">
                <label className="text-xs text-[var(--ink-secondary)] font-medium">
                  Correct Option / Answer:
                </label>
                <input
                  type="text"
                  value={editCorrectOption}
                  onChange={(e) => setEditCorrectOption(e.target.value)}
                  className="p-2 text-xs font-mono rounded border border-[var(--surface-border)] bg-[var(--surface-bg)] text-[var(--ink-primary)] focus:outline-none focus:border-[var(--accent-indigo)]"
                  placeholder="e.g. Operating system / B / 1"
                />
              </div>
            )}
            <label className="text-xs text-[var(--ink-secondary)] font-medium">
              Model Answer:
            </label>
            <textarea
              value={editModelAnswer}
              onChange={(e) => setEditModelAnswer(e.target.value)}
              className="flex-1 p-2 text-xs font-mono rounded border border-[var(--surface-border)] bg-[var(--surface-bg)] text-[var(--ink-primary)] resize-none focus:outline-none focus:border-[var(--accent-indigo)]"
              placeholder="Enter model reference answer..."
            />
            <p className="text-[10px] text-[var(--status-flagged)]">
              Note: Saving will update the paper reference and mark current evaluation as stale (Recheck Needed).
            </p>
          </div>

          <div className="pt-3 mt-3 border-t border-[var(--surface-border)] flex items-center justify-end gap-2">
            <button
              type="button"
              onClick={() => setIsDrawerOpen(false)}
              className="px-3 py-1.5 text-xs rounded border border-[var(--surface-border)] hover:bg-[var(--surface-hover)] text-[var(--ink-secondary)]"
            >
              Cancel
            </button>
            <button
              type="button"
              onClick={handleSaveReference}
              disabled={isSaving}
              className="px-3 py-1.5 text-xs font-semibold rounded bg-[var(--accent-indigo)] text-white hover:bg-[var(--accent-indigo-hover)] disabled:opacity-50 transition flex items-center gap-1.5"
            >
              <Check className="w-3.5 h-3.5" />
              {isSaving ? 'Saving...' : 'Save Reference'}
            </button>
          </div>
        </div>
      )}
    </section>
  );
};
